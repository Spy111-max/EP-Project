export const treeDetailsBySlug = Object.fromEntries(
  Object.entries(baseTreeDetailsBySlug).map(([slug, details]) => [
    slug,
    {
      ...details,
      ...defaultCultivationProfile,
      soilType: details.soilPreference,
      ...cultivationBySlug[slug],
    },
  ]),
);

export function getTreeSlugFromName(name) {
  const direct = slugify(name);
  if (treeDetailsBySlug[direct]) return direct;

  const fallback = Object.keys(treeDetailsBySlug).find((key) =>
    treeDetailsBySlug[key].commonName.toLowerCase() === String(name || "").toLowerCase(),
  );

  return fallback || "neem";
}

export function getTreeDetailsBySlug(slug) {
  return treeDetailsBySlug[slug] || null;
}
